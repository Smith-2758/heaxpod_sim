%% ========================================================================
% 函数名: bothsides_differ_spline (双边差分样条插值)
% 
% 【核心功能】
%   这是一个轨迹平滑插值函数，用于将离散的关键关节角度点转换为连续、
%   平滑的关节角度轨迹。它使用中心差分法估计关键点的速度和加速度，
%   然后使用五次样条插值生成平滑轨迹。
%
% 【应用场景】
%   在机器人轨迹规划中，我们通常只定义几个关键姿态点（如初始姿态、
%   抬腿姿态、落地姿态等），然后需要生成这些点之间的平滑过渡轨迹。
%   这个函数就是完成这个任务的。
%
% 【输入参数】
%   q_mark:    关键关节角度点矩阵 [m×n]
%               - m: 关键点的数量（例如：5个关键姿态）
%               - n: 关节数量（例如：18个关节）
%               - 单位：度（函数内部会转换为弧度）
%               示例：q_mark = [
%                     0   0  -90   0   0  -90  ...  % 初始姿态（18个关节）
%                     10  0  -90  -10  15 -105 ...  % 第一步态（18个关节）
%                     20  0  -90  -20  0  -90  ...  % 第二步态（18个关节）
%                     ...
%                   ];
%
%   period_time: 相邻两个关键点之间的时间周期（秒）
%                例如：period_time = 2 表示每个关键点之间间隔2秒
%
%   step_time:   输出轨迹的时间步长（秒）
%                例如：step_time = 0.005 表示每0.005秒一个轨迹点
%                对应200Hz的控制频率
%
%   coef:        速度/加速度估计系数（可选，默认0.25）
%                用于控制轨迹的平滑程度
%                值越大，轨迹变化越剧烈；值越小，轨迹越平滑
%
% 【输出参数】
%   Joint:       完整的关节角度轨迹矩阵 [N×n]
%                - N: 轨迹点数 = (m-1) × (period_time/step_time)
%                - n: 关节数量（与输入相同）
%                - 单位：弧度
%                示例：如果m=5, period_time=2, step_time=0.005
%                则 N = 4 × (2/0.005) = 1600个轨迹点
%
% 【算法原理】
%   1. 使用中心差分法估计每个关键点的速度和加速度
%       v[i] = coef × (q[i+1] - q[i-1]) / (2 × period_time)
%       a[i] = coef × (v[i+1] - v[i-1]) / (2 × period_time)
%
%   2. 在每两个关键点之间，使用五次样条插值生成平滑轨迹
%      - 起点：位置q[i], 速度v[i], 加速度a[i]
%      - 中点：位置(q[i]+q[i+1])/2
%      - 终点：位置q[i+1], 速度v[i+1], 加速度a[i+1]
%
%   3. 样条插值确保轨迹在位置、速度、加速度三个层面都连续平滑
%
% 【程序联动关系】
%   上游调用: walk.m, hello1.m 等步态生成函数
%             → bothsides_differ_spline(q_mark, period_time, step_time)
%   下游调用: bothsides_differ_spline → TSpline_S_V_A.m (五次样条插值)
%   下游输出: 返回给 PG.m → 传递给 CoppeliaSim_process.m 执行仿真
%
% 【使用示例】
%   % 定义5个关键关节角度点（18个关节）
%   q_mark = [
%       0   0  -90   0   0  -90   0   0  -90   0   0  -90   0   0  -90   0   0  -90;
%       10  0  -90  -10  15 -105  10  0  -90   10  15 -105 -10  0  -90   10  15 -105;
%       20  0  -90  -20  0  -90   20  0  -90   20  0  -90  -20  0  -90   20  0  -90;
%       10  15 -105 -10  0  -90   10  15 -105  10  0  -90  -10  15 -105  10  0  -90;
%       0   0  -90   0   0  -90   0   0  -90   0   0  -90   0   0  -90   0   0  -90;
%   ];
%   
%   % 生成平滑轨迹
%   Joint = bothsides_differ_spline(q_mark, 2, 0.005);
%   % 结果：Joint是一个1600×18的矩阵，包含完整的关节角度轨迹
% ========================================================================
function Joint=bothsides_differ_spline(q_mark,period_time,step_time,coef)

%% ========== 第一部分: 参数初始化和默认值设置 ==========

% 检查输入参数数量
% 如果只提供了3个参数（q_mark, period_time, step_time），则使用默认系数
if nargin==3
    coef=0.25;  % 默认速度/加速度估计系数
    % 这个系数控制轨迹的平滑程度：
    % - 值越小（如0.1）：轨迹更平滑，但可能响应较慢
    % - 值越大（如0.5）：轨迹变化更剧烈，响应更快
    % - 0.25是一个经验值，在平滑性和响应性之间取得平衡
end

%% ========== 第二部分: 获取输入数据维度 ==========

[m,n]=size(q_mark);
% m: 关键点的数量（例如：5个关键姿态）
% n: 关节数量（例如：18个关节，每条腿3个关节 × 6条腿）

x_pass=q_mark;  % 保存原始关键点数据（位置信息）

%% ========== 第三部分: 使用中心差分法估计速度 ==========
% 【算法说明】
%   中心差分法是一种数值微分方法，用于估计中间点的导数
%   公式：v[i] = (x[i+1] - x[i-1]) / (2 × Δt)
%   这种方法比前向差分或后向差分更准确

v_pass = zeros(m, n);  % 预分配速度矩阵

for ii=1:m
    if ii==1||ii==m
        % 【边界处理】第一个和最后一个关键点
        % 由于没有前一个或后一个点，无法使用中心差分
        % 因此将速度设为0（静止状态）
        v_pass(ii,:)=zeros(1,n);
    else
        % 【中心差分法】计算中间点的速度
        % 公式：v[i] = coef × (x[i+1] - x[i-1]) / (2 × period_time)
        % 
        % 解释：
        % - x[i+1] - x[i-1]: 前后两个关键点的位置差
        % - 2 × period_time: 时间间隔（从i-1到i+1是2个周期）
        % - coef: 平滑系数，用于调整速度大小
        %
        % 为什么除以2？
        %   因为中心差分法计算的是中间点的导数，时间间隔是2个周期
        v_pass(ii,:)=coef*(x_pass(ii+1,:)-x_pass(ii-1,:))/2/period_time;
    end
end

%% ========== 第四部分: 使用中心差分法估计加速度 ==========
% 【算法说明】
%   加速度是速度的导数，同样使用中心差分法计算
%   公式：a[i] = (v[i+1] - v[i-1]) / (2 × Δt)

a_pass = zeros(m, n);  % 预分配加速度矩阵

for ii=1:m
    if ii==1||ii==m
        % 【边界处理】第一个和最后一个关键点
        % 加速度也设为0（无加速度变化）
        a_pass(ii,:)=zeros(1,n);
    else
        % 【中心差分法】计算中间点的加速度
        % 公式：a[i] = coef × (v[i+1] - v[i-1]) / (2 × period_time)
        % 
        % 解释：
        % - v[i+1] - v[i-1]: 前后两个关键点的速度差
        % - 2 × period_time: 时间间隔
        % - coef: 平滑系数
        a_pass(ii,:)=coef*(v_pass(ii+1,:)-v_pass(ii-1,:))/2/period_time;
    end
end

%% ========== 第五部分: 使用样条插值生成完整轨迹 ==========
% 【核心算法】
%   在每两个关键点之间，使用五次样条插值生成平滑轨迹
%   样条插值确保轨迹在位置、速度、加速度三个层面都连续

Joint=[];  % 初始化输出轨迹矩阵

% 【外层循环】遍历每两个相邻的关键点
% 例如：如果有5个关键点，则生成4段轨迹
for kk=1:m-1
    %% --- 提取当前段的边界条件 ---
    % 起点（第kk个关键点）
    p0=x_pass(kk,:);      % 起点位置（关节角度）
    v0=v_pass(kk,:);      % 起点速度
    a0=a_pass(kk,:);      % 起点加速度
    t0=0;                 % 起点时间（相对时间，设为0）
    
    % 中点（两个关键点的中点）
    % 使用中点作为额外的约束条件，使轨迹更平滑
    p1=(x_pass(kk,:)+x_pass(kk+1,:))/2;  % 中点位置（两个关键点的平均值）
    t1=period_time/2;      % 中点时间（周期的一半）
    
    % 终点（第kk+1个关键点）
    p2=x_pass(kk+1,:);    % 终点位置（关节角度）
    v2=v_pass(kk+1,:);    % 终点速度
    a2=a_pass(kk+1,:);    % 终点加速度
    t2=period_time;        % 终点时间（一个完整周期）
    
    %% --- 调用五次样条插值函数生成轨迹段 ---
    % 【函数调用】TSpline_S_V_A
    % 功能：在起点、中点、终点之间生成五次样条插值轨迹
    % 
    % 输入参数（注意：需要转置为列向量）：
    %   p0, v0, a0, t0: 起点的位置、速度、加速度、时间
    %   p1, t1:         中点的位置、时间
    %   p2, v2, a2, t2: 终点的位置、速度、加速度、时间
    %   step_time:      输出轨迹的时间步长
    %
    % 输出：
    %   Joint_temp: 当前段的轨迹 [N_seg×n]
    %               N_seg = period_time / step_time
    %               例如：2秒 / 0.005秒 = 400个点
    %
    % 注意：函数返回的是转置后的结果，所以需要再次转置
    Joint_temp=TSpline_S_V_A(p0',v0',a0',t0,p1',t1',p2',v2',a2',t2',step_time)';
    
    %% --- 将当前段轨迹添加到总轨迹中 ---
    % 使用垂直拼接，将所有段的轨迹连接起来
    Joint=[Joint;Joint_temp];
end

%% ========== 第六部分: 轨迹后处理（可选） ==========
% 【已注释】关节限制检查
% 如果需要，可以在这里添加关节角度限制检查
% 确保生成的轨迹在关节的运动范围内
% Joint=Joint_limit(Joint);

end  % 函数结束

%% ========================================================================
% 【算法总结】
%
% 1. 【输入】离散的关键关节角度点（如5个关键姿态）
% 2. 【处理】使用中心差分法估计每个关键点的速度和加速度
% 3. 【插值】在每两个关键点之间使用五次样条插值生成平滑轨迹
% 4. 【输出】完整的关节角度轨迹（如1600个轨迹点）
%
% 【关键特点】
% - 轨迹平滑：位置、速度、加速度都连续
% - 精确控制：满足关键点的位置、速度、加速度约束
% - 计算高效：使用解析解，计算速度快
%
% 【应用示例】
% 在walk.m中：
%   q_mark = [初始姿态; 抬腿姿态; 落地姿态; ...];  % 5×18矩阵
%   Joint = bothsides_differ_spline(q_mark, 2, 0.005);  % 生成1600×18轨迹
%   结果：从5个关键点生成了1600个平滑的轨迹点
%
% 【与TSpline_S_V_A的关系】
%   bothsides_differ_spline 是高级封装函数，处理多个关键点
%   TSpline_S_V_A 是底层函数，处理两个关键点之间的插值
%   关系：bothsides_differ_spline 内部循环调用 TSpline_S_V_A
% ========================================================================